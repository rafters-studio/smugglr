/// The manifest, sealed exactly as the CLI would read one off disk.
///
/// `version: 1` is the generator's hardcoded value and the driver overrides it;
/// `target_schema` is opaque for 0.5.0. Both ops are structurally additive, so
/// the lint passes them and no pre-image is required.
fn the_migration() -> ChecksummedManifest {
    ChecksummedManifest::seal(Manifest {
        version: 1,
        target_schema: "opaque".into(),
        up: vec![
            ClassifiedOp::new(Op::AddColumn {
                table: FK_TABLE.into(),
                column: Column {
                    name: ADDED_COLUMN.into(),
                    kind: ColumnKind::Text,
                    constraints: Vec::new(),
                    tags: Vec::new(),
                },
            }),
            ClassifiedOp::new(Op::CreateTable {
                table: CREATED_TABLE.into(),
                columns: vec![
                    Column {
                        name: "id".into(),
                        kind: ColumnKind::Int,
                        constraints: vec![Constraint::Pk],
                        tags: Vec::new(),
                    },
                    Column {
                        name: "note".into(),
                        kind: ColumnKind::Text,
                        constraints: Vec::new(),
                        tags: Vec::new(),
                    },
                ],
                without_rowid: false,
            }),
        ],
        down: Vec::new(),
        preimage: None,
        flags: Flags::default(),
        author: None,
    })
    .expect("the manifest seals")
}

/// The schema the migration claims to arrive at.
///
/// Derived from the start schema by making the migration's own structural
/// changes to it, rather than authored separately. A hand-written target is a
/// second description of the same intent, and the two drift: the day it did,
/// the oracle would report a divergence about the copy rather than about the
/// engine.
///
/// `ADD COLUMN` appends, so the column is pushed onto the end of the table --
/// the from-scratch arm has to declare its columns in the order SQLite leaves
/// the migrated one in.
fn after_the_migration(start: &Schema) -> Schema {
    let mut target = start.clone();

    let altered = target
        .tables
        .iter_mut()
        .find(|existing| existing.name == FK_TABLE)
        .unwrap_or_else(|| panic!("the every-trait schema carries {FK_TABLE:?}"));
    altered.columns.push(ForgedColumn {
        name: ADDED_COLUMN.into(),
        decl_type: Some(ColumnType::Text),
        constraints: Vec::new(),
    });

    // The builder authors a whole schema rather than a bare table, so the
    // created table is written as a schema of one and folded in.
    let created = schema()
        .table(
            table(CREATED_TABLE)
                .pk_int("id")
                .col("note", ColumnType::Text, []),
        )
        .build()
        .expect("the created table is one SQLite accepts");
    target.tables.extend(created.tables);

    target
        .validate()
        .expect("the post-migration schema is one SQLite accepts");
    target
}
