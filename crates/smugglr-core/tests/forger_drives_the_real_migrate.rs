use smugglr_core::config::SyncConfig;
use smugglr_core::migrate::driver::{apply_migration, ApplyOptions};
use smugglr_core::migrate::ledger::Election;
use smugglr_core::migrate::{
    ChecksummedManifest, ClassifiedOp, Column, ColumnKind, Constraint, Flags, Manifest, Op,
};

use smugglr_forger::census::every_trait_schema;
use smugglr_forger::error::BoxError;
use smugglr_forger::fixture::Backing;
use smugglr_forger::oracle::{differential, Outcome};
use smugglr_forger::schema::builder::{schema, table};
// Renamed on import: `smugglr_core::migrate::Column` is a manifest op's column
// and this one is a schema model's. Two `Column`s in one file is a reader
// tripping over which layer they are in.
use smugglr_forger::schema::{Column as ForgedColumn, ColumnType, Schema, Trait};

/// The table in forger's every-trait schema that carries the foreign key with a
/// referential action -- the #341 table. The migration adds a column to *this*
/// one rather than to an inert table, so the apply runs over a table whose
/// behaviour the oracle is watching.
const FK_TABLE: &str = "cascade_child";

/// The column the migration adds. Named for what it is, since it lands in a
/// schema whose other column names are forger's.
const ADDED_COLUMN: &str = "migration_note";

/// The table the migration creates. It carries no trait; it is here so the
/// oracle's table inventory has something to compare that only exists because
/// migrate ran.
const CREATED_TABLE: &str = "migration_audit";

// ---------------------------------------------------------------------------
// The test
// ---------------------------------------------------------------------------

/// A real migration, applied by the real driver, over a schema carrying all
/// eight traits.
///
/// Both backings, because the oracle's arms are stood up per backing and the
/// CLI's apply reaches a file while these assertions are cheap enough to make
/// twice.
#[test]
fn the_real_apply_path_preserves_every_trait_it_migrates_over() {
    for backing in Backing::ALL {
        let start = every_trait_schema();
        let target = after_the_migration(&start);
        let sealed = the_migration();

        // The engine's own list, reached through the engine's own public
        // surface: `SyncConfig::default().exclude_tables` *is*
        // `config::default_exclude_tables()`.
        let ignore = SyncConfig::default().exclude_tables;

        let mut applied = Vec::new();
        let mut transform = |conn: &mut Connection| -> Result<(), BoxError> {
            applied.push(apply_migration(conn, &sealed, &ApplyOptions::default())?);
            Ok(())
        };

        let report = differential(backing, &start, &target, &mut transform, &ignore)
            .unwrap_or_else(|error| panic!("{backing:?}: the migration did not run: {error}"));

        // A migration that did not apply would leave both arms holding on every
        // trait, so the run has to be shown to have happened before the silence
        // is read as a result. The election is the driver's own word for it.
        let outcome = match applied.as_slice() {
            [outcome] => outcome,
            other => panic!("{backing:?}: the transformation ran {} times", other.len()),
        };
        assert_eq!(
            outcome.election,
            Election::Won,
            "{backing:?}: the driver has to have won its election, or it applied nothing"
        );
        assert_eq!(
            outcome.classifications.len(),
            sealed.manifest.up.len(),
            "{backing:?}: every op should have been linted and applied"
        );

        // Two arms that broke identically do not diverge, so "no divergence" is
        // also what a bad target schema or a mislocated probe produces. Without
        // this, every comparison below is an agreement between two wrong
        // answers.
        assert!(
            report.baseline_is_sound(),
            "{backing:?}: these did not hold in the arm built from the target schema, so nothing \
             compared against it means anything: {:?}",
            report.unsound_baseline()
        );

        for observed in &report.traits {
            assert_eq!(
                observed.transformed,
                Outcome::Held,
                "{backing:?}: {:?} did not hold after the real apply",
                observed.kind
            );
        }

        assert_eq!(
            report.divergences(),
            Vec::new(),
            "{backing:?}: the migrated database and the one built from the target schema \
             answered differently"
        );

        // Named rather than left to the loop above, because this is the trait
        // the additive path is being claimed for: the table the migration
        // altered is the table whose cascade the probe deletes through.
        assert_eq!(
            report.for_trait(Trait::ForeignKeyWithAction).transformed,
            Outcome::Held,
            "{backing:?}: ADD COLUMN on {FK_TABLE:?} lost its referential action"
        );
    }
}

